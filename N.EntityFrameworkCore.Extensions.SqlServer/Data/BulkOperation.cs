using System;
using System.Collections.Generic;
using System.Data.Common;
using System.IO;
using System.Linq;
using System.Linq.Expressions;
using Microsoft.Data.SqlClient;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata;
using N.EntityFrameworkCore.Extensions.Common;
using N.EntityFrameworkCore.Extensions.Sql;
using N.EntityFrameworkCore.Extensions.Util;

namespace N.EntityFrameworkCore.Extensions;

internal sealed partial class BulkOperation<T> : IDisposable
{
    internal DbConnection Connection => DbTransactionContext.Connection;
    internal DbContext Context { get; }
    internal bool StagingTableCreated { get; set; }
    internal string StagingTableName { get; }
    internal string[] PrimaryKeyColumnNames { get; }
    internal BulkOptions Options { get; }
    internal Expression<Func<T, object>> InputColumns { get; }
    internal Expression<Func<T, object>> IgnoreColumns { get; }
    internal Expression<Func<T, object>> InputColumnsOnInsert { get; }
    internal Expression<Func<T, object>> IgnoreColumnsOnInsert { get; }
    internal Expression<Func<T, object>> InputColumnsOnUpdate { get; }
    internal Expression<Func<T, object>> IgnoreColumnsOnUpdate { get; }
    internal Expression<Func<T, object>> SoftDeleteColumns { get; }
    internal bool UseNativeUpsert { get; }
    internal DbTransactionContext DbTransactionContext { get; }
    internal Type EntityType => typeof(T);
    internal DbTransaction Transaction => DbTransactionContext.CurrentTransaction;
    internal TableMapping TableMapping { get; }
    internal IEnumerable<string> SchemaQualifiedTableNames => TableMapping.GetSchemaQualifiedTableNames();

    public BulkOperation(DbContext dbContext, BulkOptions options, Expression<Func<T, object>> inputColumns = null, Expression<Func<T, object>> ignoreColumns = null)
    {
        Context = dbContext;
        Options = options;
        InputColumns = inputColumns;
        IgnoreColumns = ignoreColumns;

        DbTransactionContext = new DbTransactionContext(dbContext, options.CommandTimeout);
        TableMapping = dbContext.GetTableMapping(typeof(T), options.EntityType);
        StagingTableName = CommonUtil.GetStagingTableName(TableMapping, options.UsePermanentTable, Connection);
        PrimaryKeyColumnNames = TableMapping.GetPrimaryKeyColumns().ToArray();
    }
    public BulkOperation(DbContext dbContext, BulkMergeOptions<T> mergeOptions)
        : this(dbContext, mergeOptions, mergeOptions.InputColumnsOnInsert, mergeOptions.IgnoreColumnsOnInsert)
    {
        InputColumnsOnUpdate = mergeOptions.InputColumnsOnUpdate;
        IgnoreColumnsOnUpdate = mergeOptions.IgnoreColumnsOnUpdate;
        SoftDeleteColumns = mergeOptions.SoftDeleteColumns;
        UseNativeUpsert = mergeOptions.UseNativeUpsert;
    }
    public void Dispose()
    {
        if (StagingTableCreated && !Options.UsePermanentTable)
            Context.Database.DropTable(StagingTableName, true);
        DbTransactionContext.Dispose();
    }
    internal BulkInsertResult<T> BulkInsertStagingData(IEnumerable<T> entities, bool keepIdentity = true, bool useInternalId = false)
    {
        IEnumerable<string> columnsToInsert = GetColumnNames(keepIdentity);
        string internalIdColumn = useInternalId ? Common.Constants.InternalId_ColumnName : null;
        Context.Database.CloneTable(SchemaQualifiedTableNames, StagingTableName, TableMapping.GetQualifiedColumnNames(columnsToInsert), internalIdColumn);
        StagingTableCreated = true;
        return DbContextExtensions.BulkInsert(entities, Options, TableMapping, Connection, Transaction, StagingTableName, columnsToInsert, SqlBulkCopyOptions.KeepIdentity, useInternalId);
    }
    internal BulkMergeResult<T> ExecuteMerge(Dictionary<long, T> entityMap, Expression<Func<T, T, bool>> mergeOnCondition,
        bool autoMapOutput, bool keepIdentity, bool insertIfNotExists, bool update = false, bool delete = false)
    {
        Dictionary<IEntityType, int> rowsInserted = [];
        Dictionary<IEntityType, int> rowsUpdated = [];
        Dictionary<IEntityType, int> rowsDeleted = [];
        Dictionary<IEntityType, int> rowsAffected = [];
        List<BulkMergeOutputRow<T>> outputRows = [];
        bool fireTriggers = Options.FireTriggers;

        foreach (var entityType in TableMapping.EntityTypes)
        {
            rowsInserted[entityType] = 0;
            rowsUpdated[entityType] = 0;
            rowsDeleted[entityType] = 0;
            rowsAffected[entityType] = 0;

            var columnsToInsert = GetInsertColumnNames(entityType, keepIdentity);
            var columnsToUpdate = update ? GetUpdateColumnNames(entityType) : [];
            var autoGeneratedColumns = autoMapOutput ? TableMapping.GetAutoGeneratedColumns(entityType) : [];
            // SQL Server disallows MERGE...OUTPUT when the target has triggers (#51/#88)
            var columnsToOutput = autoMapOutput && !fireTriggers ? GetMergeOutputColumns(autoGeneratedColumns, delete) : [];
            bool deleteEntityType = TableMapping.EntityType == entityType && delete && SoftDeleteColumns == null;

            string mergeOnConditionSql = (insertIfNotExists || mergeOnCondition != null)
                ? CommonUtil<T>.GetJoinConditionSql(Context, mergeOnCondition, PrimaryKeyColumnNames, "t", "s")
                : "1=2";
            bool toggleIdentity = keepIdentity && TableMapping.HasIdentityColumn;
            var mergeStatement = SqlStatement.CreateMerge(StagingTableName, entityType.GetSchemaQualifiedTableName(),
                mergeOnConditionSql, columnsToInsert, columnsToUpdate, columnsToOutput, deleteEntityType, toggleIdentity);

            List<IProperty> allProperties =
            [
                .. TableMapping.GetEntityProperties(entityType, ValueGenerated.OnAdd).ToArray(),
                .. TableMapping.GetEntityProperties(entityType, ValueGenerated.OnAddOrUpdate).ToArray()
            ];

            if (autoMapOutput && !fireTriggers)
            {
                var bulkQueryResult = Context.BulkQuery(mergeStatement.Sql, Options);
                rowsAffected[entityType] = bulkQueryResult.RowsAffected;

                foreach (var result in bulkQueryResult.Results)
                {
                    string action = (string)result[0];
                    outputRows.Add(new BulkMergeOutputRow<T>(action));

                    if (action == SqlMergeAction.Delete)
                    {
                        rowsDeleted[entityType]++;
                    }
                    else
                    {
                        int entityId = (int)result[1];
                        var entity = entityMap[entityId];
                        if (action == SqlMergeAction.Insert)
                        {
                            rowsInserted[entityType]++;
                            if (allProperties.Count != 0)
                            {
                                var entityValues = GetMergeOutputValues(columnsToOutput, result, allProperties);
                                Context.SetStoreGeneratedValues(entity, allProperties, entityValues);
                            }
                        }
                        else if (action == SqlMergeAction.Update)
                        {
                            rowsUpdated[entityType]++;
                            if (allProperties.Count != 0)
                            {
                                var entityValues = GetMergeOutputValues(columnsToOutput, result, allProperties);
                                Context.SetStoreGeneratedValues(entity, allProperties, entityValues);
                            }
                        }
                    }
                }
            }
            else
            {
                object maxIdentityBefore = null;
                var identityProperty = GetSqlIdentityPrimaryKeyProperty(entityType);
                if (fireTriggers && autoMapOutput && identityProperty != null && !keepIdentity && !update && !delete && !insertIfNotExists)
                    maxIdentityBefore = ReadMaxIdentityValue(entityType, identityProperty);

                rowsAffected[entityType] = Context.Database.ExecuteSqlInternal(mergeStatement.Sql, Options.CommandTimeout);

                if (fireTriggers && autoMapOutput)
                {
                    if (identityProperty != null && !keepIdentity && !update && !delete && !insertIfNotExists)
                    {
                        int mapped = MapIdentityValuesAfterTriggerInsert(entityMap, entityType, identityProperty, maxIdentityBefore);
                        rowsInserted[entityType] = mapped;
                    }
                    else
                    {
                        rowsInserted[entityType] = rowsAffected[entityType];
                    }
                }
            }

            if (TableMapping.EntityType == entityType && delete && SoftDeleteColumns != null)
            {
                string setExpression = SoftDeleteColumns.ToSqlConstantUpdateSetExpression(Context);
                string targetTable = CommonUtil.FormatTableName(entityType.GetSchemaQualifiedTableName());
                string softDeleteSql = $"UPDATE t SET {setExpression} FROM {targetTable} AS t WHERE NOT EXISTS (SELECT 1 FROM {StagingTableName} AS s WHERE {mergeOnConditionSql})";
                rowsDeleted[entityType] = Context.Database.ExecuteSqlInternal(softDeleteSql, Options.CommandTimeout);
                for (int i = 0; i < rowsDeleted[entityType]; i++)
                    outputRows.Add(new BulkMergeOutputRow<T>(SqlMergeAction.Delete));
            }
        }
        return new BulkMergeResult<T>
        {
            Output = outputRows,
            RowsAffected = GetLogicalRowCount(rowsAffected),
            RowsDeleted = GetLogicalRowCount(rowsDeleted),
            RowsInserted = GetLogicalRowCount(rowsInserted),
            RowsUpdated = GetLogicalRowCount(rowsUpdated)
        };
    }

    private static IProperty GetSqlIdentityPrimaryKeyProperty(IEntityType entityType)
    {
        var pk = entityType.FindPrimaryKey();
        if (pk == null || pk.Properties.Count != 1)
            return null;
        var property = pk.Properties[0];
        return IsSqlServerIdentityColumn(property) ? property : null;
    }

    private static bool IsSqlServerIdentityColumn(IProperty property)
    {
        var strategy = property.FindAnnotation("SqlServer:ValueGenerationStrategy")?.Value?.ToString();
        return string.Equals(strategy, "IdentityColumn", StringComparison.Ordinal);
    }

    private object ReadMaxIdentityValue(IEntityType entityType, IProperty identityProperty)
    {
        string tableName = CommonUtil.FormatTableName(entityType.GetSchemaQualifiedTableName());
        string columnName = TableMapping.GetColumnName(identityProperty);
        string sql = $"SELECT MAX({Context.DelimitIdentifier(columnName)}) FROM {tableName}";
        var result = Context.BulkQuery(sql, Options);
        var firstRow = result.Results.FirstOrDefault();
        return firstRow?.FirstOrDefault() is DBNull or null ? null : firstRow[0];
    }

    private int MapIdentityValuesAfterTriggerInsert(Dictionary<long, T> entityMap, IEntityType entityType, IProperty identityProperty, object maxIdentityBefore)
    {
        string tableName = CommonUtil.FormatTableName(entityType.GetSchemaQualifiedTableName());
        string columnName = TableMapping.GetColumnName(identityProperty);
        string maxFilter = maxIdentityBefore == null || maxIdentityBefore is DBNull
            ? "1=1"
            : $"{Context.DelimitIdentifier(columnName)} > {Convert.ToString(maxIdentityBefore, System.Globalization.CultureInfo.InvariantCulture)}";
        string sql = $@"
SELECT s.[{Constants.InternalId_ColumnName}] AS InternalId, x.{Context.DelimitIdentifier(columnName)} AS GeneratedId
FROM (
    SELECT [{Constants.InternalId_ColumnName}], ROW_NUMBER() OVER (ORDER BY [{Constants.InternalId_ColumnName}]) AS rn
    FROM {StagingTableName}
) s
INNER JOIN (
    SELECT {Context.DelimitIdentifier(columnName)}, ROW_NUMBER() OVER (ORDER BY {Context.DelimitIdentifier(columnName)}) AS rn
    FROM {tableName}
    WHERE {maxFilter}
) x ON x.rn = s.rn";

        var queryResult = Context.BulkQuery(sql, Options);
        int mapped = 0;
        foreach (var row in queryResult.Results)
        {
            long internalId = Convert.ToInt64(row[0]);
            if (!entityMap.TryGetValue(internalId, out var entity))
                continue;
            object generated = Convert.ChangeType(row[1], Nullable.GetUnderlyingType(identityProperty.ClrType) ?? identityProperty.ClrType);
            Context.SetStoreGeneratedValues(entity, [identityProperty], [generated]);
            mapped++;
        }
        return mapped;
    }

    private IEnumerable<string> GetMergeOutputColumns(IEnumerable<string> autoGeneratedColumns, bool delete = false)
    {
        List<string> columnsToOutput = ["$action", $"[s].[{Constants.InternalId_ColumnName}]"];
        columnsToOutput.AddRange(autoGeneratedColumns.Select(o => $"[inserted].[{o}]"));
        return columnsToOutput;
    }
    private object[] GetMergeOutputValues(IEnumerable<string> columns, object[] values, IEnumerable<IProperty> properties)
    {
        var columnList = columns.ToList();
        var valuesIndex = properties.Select(o => columnList.IndexOf($"[inserted].[{o.GetColumnName()}]"));
        return valuesIndex.Select(i => values[i]).ToArray();
    }
    internal int ExecuteUpdate(IEnumerable<T> entities, Expression<Func<T, T, bool>> updateOnCondition)
    {
        int rowsUpdated = 0;
        foreach (var entityType in TableMapping.EntityTypes)
        {
            IEnumerable<string> columnsToUpdate = CommonUtil.FormatColumns(GetColumnNames(entityType));
            string updateSetExpression = string.Join(",", columnsToUpdate.Select(o => $"t.{o}=s.{o}"));
            string updateSql = $"UPDATE t SET {updateSetExpression} FROM {StagingTableName} AS s JOIN {CommonUtil.FormatTableName(entityType.GetSchemaQualifiedTableName())} AS t ON {CommonUtil<T>.GetJoinConditionSql(Context, updateOnCondition, PrimaryKeyColumnNames, "s", "t")}; SELECT @@RowCount;";
            rowsUpdated = Math.Max(rowsUpdated, Context.Database.ExecuteSqlInternal(updateSql, Options.CommandTimeout));
        }
        return rowsUpdated;
    }
    private static int GetLogicalRowCount(Dictionary<IEntityType, int> rowCounts)
    {
        return rowCounts.Values.DefaultIfEmpty(0).Max();
    }
    internal void ValidateBulkMerge(Expression<Func<T, T, bool>> mergeOnCondition)
    {
        if (PrimaryKeyColumnNames.Length == 0 && mergeOnCondition == null)
            throw new InvalidDataException("BulkMerge requires that the entity have a primary key or that Options.MergeOnCondition be set");
    }
    internal void ValidateBulkUpdate(Expression<Func<T, T, bool>> updateOnCondition)
    {
        if (PrimaryKeyColumnNames.Length == 0 && updateOnCondition == null)
            throw new InvalidDataException("BulkUpdate requires that the entity have a primary key or the Options.UpdateOnCondition must be set.");
    }
    internal IEnumerable<string> GetColumnNames(bool includePrimaryKeys = false)
    {
        return GetColumnNames(null, includePrimaryKeys);
    }
    internal IEnumerable<string> GetColumnNames(IEntityType entityType, bool includePrimaryKeys = false)
    {
        return CommonUtil.FilterColumns(TableMapping.GetColumnNames(entityType, includePrimaryKeys), PrimaryKeyColumnNames, InputColumns, IgnoreColumns);
    }
    internal IEnumerable<string> GetInsertColumnNames(IEntityType entityType = null, bool includePrimaryKeys = false)
    {
        return CommonUtil.FilterColumns(TableMapping.GetColumnNames(entityType, includePrimaryKeys), PrimaryKeyColumnNames,
            InputColumnsOnInsert ?? InputColumns, IgnoreColumnsOnInsert ?? IgnoreColumns);
    }
    internal IEnumerable<string> GetUpdateColumnNames(IEntityType entityType = null)
    {
        return CommonUtil.FilterColumns(TableMapping.GetColumnNames(entityType, false), PrimaryKeyColumnNames,
            InputColumnsOnUpdate ?? InputColumns, IgnoreColumnsOnUpdate ?? IgnoreColumns);
    }
}