    internal static int BulkInsert<T>(DbContext context, IEnumerable<T> entities, BulkInsertOptions<T> options)
    {
        var items = entities?.ToList() ?? [];
        if (items.Count == 0)
            return 0;

        var tableMapping = context.GetTableMapping(typeof(T), options?.EntityType);
        if (options?.InsertIfNotExists == true || options?.InsertOnCondition != null)
            items = FilterInsertItems(context, tableMapping, items, options);

        if (items.Count == 0)
            return 0;

        var allowedColumns = GetInsertColumns(tableMapping, options?.InputColumns, options?.IgnoreColumns, options?.KeepIdentity ?? false);
        foreach (var item in items)
        {
            ApplyInsertColumnRules(item!, tableMapping, allowedColumns, options?.KeepIdentity ?? false);
        }

        ApplyInsertDefaults(context, tableMapping, items, options?.KeepIdentity ?? false);

        IProperty identityProperty = null;
        object maxIdentityBefore = null;
        bool autoMapOutput = options?.AutoMapOutput ?? false;
        if (autoMapOutput && !(options?.KeepIdentity ?? false))
        {
            identityProperty = GetIdentityPrimaryKeyProperty(tableMapping);
            if (identityProperty != null)
                maxIdentityBefore = ReadMaxIdentityValue(context, tableMapping, identityProperty);
        }

        // TPT maps one entity to multiple physical tables, so each table gets its own bulk copy.
        ExecuteOracleBulkCopyForMappedTables(context, items, tableMapping, allowedColumns, options?.CommandTimeout, options);

        if (autoMapOutput)
            MapAutoGeneratedValuesAfterInsert(context, tableMapping, items, options?.KeepIdentity ?? false, identityProperty, maxIdentityBefore);

        return items.Count;
    }

    internal static int BulkInsertIntoTable<T>(DbContext context, IEnumerable<T> entities, TableMapping tableMapping, string tableName, IEnumerable<string> columns, int? commandTimeout)
    {
        var items = entities?.ToList() ?? [];
        if (items.Count == 0)
            return 0;

        return ExecuteOracleBulkCopy(context, items, tableMapping, columns, commandTimeout, tableName);
    }

    private static int ExecuteOracleBulkCopy<T>(DbContext context, List<T> items, TableMapping tableMapping, IEnumerable<string> allowedColumns, int? commandTimeout = null, string destinationTableName = null, bool useInternalId = false, Dictionary<long, T> entityMap = null, BulkOptions progressOptions = null)
    {
        var columns = allowedColumns?.Distinct(StringComparer.OrdinalIgnoreCase).ToList() ?? [];
        if (items.Count == 0 || columns.Count == 0)
            return 0;

        var connection = (OracleConnection)context.Database.GetDbConnection();
        if (connection.State != ConnectionState.Open)
            connection.Open();

        using var dataReader = new EntityDataReader<T>(tableMapping, items, useInternalId);
        using var bulkCopy = new OracleBulkCopy(connection);

        bulkCopy.DestinationTableName = destinationTableName ?? tableMapping.FullQualifedTableName;
        bulkCopy.BatchSize = progressOptions?.BatchSize > 0 ? progressOptions.BatchSize : items.Count;
        if (commandTimeout.HasValue)
            bulkCopy.BulkCopyTimeout = commandTimeout.Value;

        foreach (var column in columns)
        {
            bulkCopy.ColumnMappings.Add(column, context.DelimitIdentifier(column));
        }

        if (useInternalId)
            bulkCopy.ColumnMappings.Add(Constants.InternalId_ColumnName, context.DelimitIdentifier(Constants.InternalId_ColumnName));

        bulkCopy.WriteToServer(dataReader);

        if (entityMap != null)
        {
            foreach (var kvp in dataReader.EntityMap)
                entityMap[kvp.Key] = kvp.Value;
        }

        if (progressOptions != null)
            BulkProgress.NotifyFinal(progressOptions, items.Count);

        return items.Count;
    }

    private static void ExecuteOracleBulkCopyForMappedTables<T>(DbContext context, List<T> items, TableMapping tableMapping, IEnumerable<string> allowedColumns, int? commandTimeout = null, BulkInsertOptions<T> options = null)
    {
        var allowed = allowedColumns?.ToHashSet(StringComparer.OrdinalIgnoreCase) ?? [];
        foreach (var entityType in tableMapping.EntityTypes)
        {
            var tableColumns = tableMapping.GetColumnNames(entityType, true)
                .Where(column => allowed.Count == 0 || allowed.Contains(column))
                .Distinct(StringComparer.OrdinalIgnoreCase)
                .ToList();

            if (tableColumns.Count == 0)
                continue;

            var tableName = context.DelimitIdentifier(entityType.GetTableName(), entityType.GetSchema() ?? context.Database.GetDefaultSchema());
            if (context.Database.CurrentTransaction != null)
                ExecuteOracleArrayInsert(context, items, tableMapping, tableColumns, commandTimeout, tableName, options);
            else
                ExecuteOracleBulkCopy(context, items, tableMapping, tableColumns, commandTimeout, tableName, progressOptions: options);
        }
    }

    private static int ExecuteOracleArrayInsert<T>(DbContext context, List<T> items, TableMapping tableMapping, IEnumerable<string> allowedColumns, int? commandTimeout, string destinationTableName, BulkOptions progressOptions = null)
    {
        var columns = allowedColumns?.Distinct(StringComparer.OrdinalIgnoreCase).ToList() ?? [];
        if (items.Count == 0 || columns.Count == 0)
            return 0;

        var connection = (OracleConnection)context.Database.GetDbConnection();
        if (connection.State != ConnectionState.Open)
            connection.Open();

        using var command = connection.CreateCommand();
        ConfigureCommand(context, command, string.Empty, commandTimeout);
        var insertColumns = columns.Select(column => $"\"{column}\"");
        var parameters = columns.Select((_, index) => $":p{index}").ToList();
        command.CommandText = $"INSERT INTO {destinationTableName} ({string.Join(", ", insertColumns)}) VALUES ({string.Join(", ", parameters)})";

        var properties = columns
            .Select(column => tableMapping.Properties.FirstOrDefault(p => string.Equals(tableMapping.GetColumnName(p), column, StringComparison.OrdinalIgnoreCase)))
            .ToList();

        var rowsInserted = 0;
        long lastNotified = 0;
        foreach (var item in items)
        {
            command.Parameters.Clear();
            for (var i = 0; i < columns.Count; i++)
            {
                var value = properties[i] == null ? null : GetPropertyValue(item!, properties[i]);
                command.Parameters.Add(new OracleParameter
                {
                    ParameterName = $"p{i}",
                    Value = value ?? DBNull.Value
                });
            }

            rowsInserted += command.ExecuteNonQuery();
            if (progressOptions != null)
                BulkProgress.Notify(progressOptions, ref lastNotified, rowsInserted);
        }

        if (progressOptions != null)
            BulkProgress.NotifyFinal(progressOptions, rowsInserted);

        return rowsInserted;
    }

    private static int ExecuteNonQuery(DbContext context, string sql, int? commandTimeout = null)
    {
        var connection = context.Database.GetDbConnection();
        if (connection.State != ConnectionState.Open)
            connection.Open();

        using var command = connection.CreateCommand();
        ConfigureCommand(context, command, sql, commandTimeout);
        int rowsAffected = command.ExecuteNonQuery();
        return rowsAffected < 0 ? 0 : rowsAffected;
    }

    private static void ConfigureCommand(DbContext context, IDbCommand command, string sql, int? commandTimeout)
    {
        command.CommandText = sql;
        command.CommandTimeout = commandTimeout ?? 300;
        if (context.Database.CurrentTransaction != null)
            command.Transaction = context.Database.CurrentTransaction.GetDbTransaction();
    }

    private static string CreateStagingTable(DbContext context, TableMapping tableMapping, bool includeInternalId = false, bool usePermanentTable = false)
    {
        string stagingTableName = $"{(usePermanentTable ? "STG_PERM" : "STG")}_{tableMapping.TableName}_{Guid.NewGuid().ToString("N")[..8]}";

        var columns = tableMapping.GetColumns(true);
        var columnDefs = new List<string>();

        foreach (var column in columns)
        {
            var property = tableMapping.Properties.FirstOrDefault(p =>
                string.Equals(tableMapping.GetColumnName(p), column, StringComparison.OrdinalIgnoreCase));

            string oracleType = property != null
                ? GetOracleColumnType(property)
                : "NVARCHAR2(4000)";
            columnDefs.Add($"{context.DelimitIdentifier(column)} {oracleType}");
        }

        if (includeInternalId)
            columnDefs.Add($"{context.DelimitIdentifier(Constants.InternalId_ColumnName)} NUMBER(10)");

        if (columnDefs.Count == 0)
            throw new InvalidOperationException($"Unable to create staging table for '{tableMapping.TableName}' because no columns were resolved.");

        string createTableSql = usePermanentTable
            ? $"CREATE TABLE {stagingTableName} ({string.Join(", ", columnDefs)})"
            : $"CREATE GLOBAL TEMPORARY TABLE {stagingTableName} ({string.Join(", ", columnDefs)}) ON COMMIT PRESERVE ROWS";
        ExecuteNonQuery(context, createTableSql);
        return stagingTableName;
    }

    private static void DropStagingTable(DbContext context, string stagingTableName, bool usePermanentTable = false)
    {
        if (!usePermanentTable && context.Database.CurrentTransaction != null)
            return;

        try
        {
            ExecuteNonQuery(context, $"DROP TABLE {stagingTableName}");
        }
        catch
        {
            // Ignore errors when dropping staging table
        }
    }

    private static int ExecuteSoftDeleteFromStaging<T>(DbContext context, TableMapping tableMapping, string stagingTableName, Expression<Func<T, T, bool>> condition, string[] pkColumnNames, IEnumerable<string> softDeleteColumns, string tableName = null)
    {
        tableName ??= tableMapping.FullQualifedTableName;
        string joinClause = CommonUtil<T>.GetJoinConditionSql(context, condition, pkColumnNames, "s", "t");
        var setClauses = softDeleteColumns.Select(col => $"{context.DelimitMemberAccess("t", col)} = {context.DelimitMemberAccess("s", col)}");
        string setClause = string.Join(", ", setClauses);

        string updateSql = $@"MERGE INTO {tableName} t
USING {stagingTableName} s
ON ({joinClause})
WHEN MATCHED THEN UPDATE SET {setClause}";

        return ExecuteNonQuery(context, updateSql);
    }

    private static int ExecuteSoftDeleteFromStagingForMappedTables<T>(DbContext context, TableMapping tableMapping, string stagingTableName, Expression<Func<T, T, bool>> condition, string[] pkColumnNames, IEnumerable<string> softDeleteColumns)
    {
        int rowsUpdated = 0;
        foreach (var entityType in tableMapping.EntityTypes)
        {
            var tableColumns = tableMapping.GetColumnNames(entityType, true)
                .ToHashSet(StringComparer.OrdinalIgnoreCase);
            var tableSoftDeleteColumns = softDeleteColumns.Where(tableColumns.Contains).ToList();
            if (tableSoftDeleteColumns.Count == 0)
                continue;

            var tableName = context.DelimitIdentifier(entityType.GetTableName(), entityType.GetSchema() ?? context.Database.GetDefaultSchema());
            rowsUpdated += ExecuteSoftDeleteFromStaging(context, tableMapping, stagingTableName, condition, pkColumnNames, tableSoftDeleteColumns, tableName);
        }

        return rowsUpdated;
    }

    private static int ExecuteDeleteFromStaging<T>(DbContext context, TableMapping tableMapping, string stagingTableName, Expression<Func<T, T, bool>> condition, string[] pkColumnNames, string tableName = null)
    {
        tableName ??= tableMapping.FullQualifedTableName;
        string joinClause = CommonUtil<T>.GetJoinConditionSql(context, condition, pkColumnNames, "s", "t");

        string deleteSql = $@"DELETE FROM {tableName} t 
WHERE EXISTS (SELECT 1 FROM {stagingTableName} s WHERE {joinClause})";

        return ExecuteNonQuery(context, deleteSql);
    }

    private static int ExecuteDeleteFromStagingForMappedTables<T>(DbContext context, TableMapping tableMapping, string stagingTableName, Expression<Func<T, T, bool>> condition, string[] pkColumnNames)
    {
        int rowsDeleted = 0;
        foreach (var entityType in tableMapping.EntityTypes.Reverse())
        {
            var tableName = context.DelimitIdentifier(entityType.GetTableName(), entityType.GetSchema() ?? context.Database.GetDefaultSchema());
            int tableRows = ExecuteDeleteFromStaging(context, tableMapping, stagingTableName, condition, pkColumnNames, tableName);
            rowsDeleted = Math.Max(rowsDeleted, tableRows);
        }

        return rowsDeleted;
    }

    private static int ExecuteMergeForUpdate<T>(DbContext context, TableMapping tableMapping, string stagingTableName, Expression<Func<T, T, bool>> condition, string[] pkColumnNames, IEnumerable<string> updatableColumns, string tableName = null)
    {
        tableName ??= tableMapping.FullQualifedTableName;
        var onColumns = GetMergeOnColumnNames(tableMapping, condition, pkColumnNames);
        var updateColumns = updatableColumns
            .Where(col => !onColumns.Contains(col))
            .ToList();

        if (updateColumns.Count == 0)
            return 0;

        string joinClause = CommonUtil<T>.GetJoinConditionSql(context, condition, pkColumnNames, "s", "t");
        var setClauses = updateColumns.Select(col => $"{context.DelimitMemberAccess("t", col)} = {context.DelimitMemberAccess("s", col)}");
        string setClause = string.Join(", ", setClauses);

        string updateSql = $@"MERGE INTO {tableName} t
USING {stagingTableName} s
ON ({joinClause})
WHEN MATCHED THEN UPDATE SET {setClause}";

        return ExecuteNonQuery(context, updateSql);
    }

    private static int ExecuteMergeForUpdateForMappedTables<T>(DbContext context, TableMapping tableMapping, string stagingTableName, Expression<Func<T, T, bool>> condition, string[] pkColumnNames, IEnumerable<string> updatableColumns)
    {
        var updateColumns = updatableColumns.Distinct(StringComparer.OrdinalIgnoreCase).ToList();
        var rowsUpdated = 0;
        var onColumns = GetMergeOnColumnNames<T>(tableMapping, condition, pkColumnNames);

        foreach (var entityType in tableMapping.EntityTypes)
        {
            var tableColumns = tableMapping.GetColumnNames(entityType, true)
                .Distinct(StringComparer.OrdinalIgnoreCase)
                .ToHashSet(StringComparer.OrdinalIgnoreCase);

            var tableUpdateColumns = updateColumns
                .Where(tableColumns.Contains)
                .Where(col => !onColumns.Contains(col))
                .ToList();
            if (tableUpdateColumns.Count == 0)
                continue;

            var tableName = context.DelimitIdentifier(entityType.GetTableName(), entityType.GetSchema() ?? context.Database.GetDefaultSchema());
            int tableRowsUpdated = ExecuteMergeForUpdate(context, tableMapping, stagingTableName, condition, pkColumnNames, tableUpdateColumns, tableName);
            rowsUpdated = Math.Max(rowsUpdated, tableRowsUpdated);
        }

        return rowsUpdated;
    }

    private static (int rowsInserted, int rowsUpdated) ExecuteMergeForMerge<T>(
        DbContext context,
        TableMapping tableMapping,
        string stagingTableName,
        Expression<Func<T, T, bool>> condition,
        string[] pkColumnNames,
        IEnumerable<string> insertColumns,
        IEnumerable<string> updatableColumns,
        string tableName = null)
    {
        tableName ??= tableMapping.FullQualifedTableName;
        var insertCols = insertColumns.ToList();
        var onColumns = GetMergeOnColumnNames<T>(tableMapping, condition, pkColumnNames);
        var updateCols = updatableColumns
            .Where(col => !onColumns.Contains(col))
            .ToList();

        if (pkColumnNames.Length == 0 && condition == null)
            return (0, 0);

        string mergeCondition = CommonUtil<T>.GetJoinConditionSql(context, condition, pkColumnNames, "s", "t");

        int rowsUpdated = 0;
        int rowsInserted = 0;

        if (updateCols.Count > 0)
        {
            var setClauses = updateCols.Select(col => $"{context.DelimitMemberAccess("t", col)} = {context.DelimitMemberAccess("s", col)}");
            string setClause = string.Join(", ", setClauses);
            string updateMergeSql = $@"MERGE INTO {tableName} t
USING {stagingTableName} s
ON ({mergeCondition})
WHEN MATCHED THEN UPDATE SET {setClause}";
            rowsUpdated = ExecuteNonQuery(context, updateMergeSql);
        }

        if (insertCols.Count > 0)
        {
            var insertColNames = insertCols.Select(col => context.DelimitIdentifier(col));
            var insertStagingCols = insertCols.Select(col => context.DelimitMemberAccess("s", col));
            string insertMergeSql = $@"MERGE INTO {tableName} t
USING {stagingTableName} s
ON ({mergeCondition})
WHEN NOT MATCHED THEN INSERT ({string.Join(", ", insertColNames)}) VALUES ({string.Join(", ", insertStagingCols)})";
            rowsInserted = ExecuteNonQuery(context, insertMergeSql);
        }

        return (rowsInserted, rowsUpdated);
    }

    private static (int rowsInserted, int rowsUpdated) ExecuteMergeForMergeForMappedTables<T>(
        DbContext context,
        TableMapping tableMapping,
        string stagingTableName,
        Expression<Func<T, T, bool>> condition,
        string[] pkColumnNames,
        IEnumerable<string> insertColumns,
        IEnumerable<string> updatableColumns)
    {
        var insertCols = insertColumns.Distinct(StringComparer.OrdinalIgnoreCase).ToList();
        var updateCols = updatableColumns.Distinct(StringComparer.OrdinalIgnoreCase).ToList();
        var rowsInserted = 0;
        var rowsUpdated = 0;
        var onColumns = GetMergeOnColumnNames<T>(tableMapping, condition, pkColumnNames);

        foreach (var entityType in tableMapping.EntityTypes)
        {
            var tableColumns = tableMapping.GetColumnNames(entityType, true)
                .Distinct(StringComparer.OrdinalIgnoreCase)
                .ToHashSet(StringComparer.OrdinalIgnoreCase);

            var tableInsertColumns = insertCols
                .Where(tableColumns.Contains)
                .ToList();
            var tableUpdateColumns = updateCols
                .Where(tableColumns.Contains)
                .Where(col => !onColumns.Contains(col))
                .ToList();

            if (tableInsertColumns.Count == 0 && tableUpdateColumns.Count == 0)
                continue;

            var tableName = context.DelimitIdentifier(entityType.GetTableName(), entityType.GetSchema() ?? context.Database.GetDefaultSchema());
            var (tableRowsInserted, tableRowsUpdated) = ExecuteMergeForMerge(
                context,
                tableMapping,
                stagingTableName,
                condition,
                pkColumnNames,
                tableInsertColumns,
                tableUpdateColumns,
                tableName);

            rowsInserted = Math.Max(rowsInserted, tableRowsInserted);
            rowsUpdated = Math.Max(rowsUpdated, tableRowsUpdated);
        }

        return (rowsInserted, rowsUpdated);
    }

    private static int ExecuteDeleteUnmatched<T>(DbContext context, string tableName, string stagingTableName, Expression<Func<T, T, bool>> condition, string[] pkColumnNames)
    {
        if (pkColumnNames.Length == 0 && condition == null)
            return 0;

        string matchJoinCondition = CommonUtil<T>.GetJoinConditionSql(context, condition, pkColumnNames, "s", "t");
        string pkJoinCondition = CommonUtil<T>.GetJoinConditionSql(context, null, pkColumnNames, "s", "t");
        string joinClause = matchJoinCondition == pkJoinCondition
            ? matchJoinCondition
            : $"({matchJoinCondition}) OR ({pkJoinCondition})";

        string deleteSql = $@"DELETE FROM {tableName} t 
WHERE NOT EXISTS (SELECT 1 FROM {stagingTableName} s WHERE {joinClause})";

        return ExecuteNonQuery(context, deleteSql);
    }

    private static int ExecuteDeleteUnmatchedForMappedTables<T>(DbContext context, TableMapping tableMapping, string stagingTableName, Expression<Func<T, T, bool>> condition, string[] pkColumnNames)
    {
        var entityType = tableMapping.EntityType;
        var tableName = context.DelimitIdentifier(entityType.GetTableName(), entityType.GetSchema() ?? context.Database.GetDefaultSchema());
        return ExecuteDeleteUnmatched<T>(context, tableName, stagingTableName, condition, pkColumnNames);
    }

    private static int ExecuteSoftDeleteUnmatched<T>(DbContext context, string tableName, string stagingTableName, Expression<Func<T, T, bool>> condition, string[] pkColumnNames, Expression<Func<T, object>> softDeleteColumns)
    {
        if (pkColumnNames.Length == 0 && condition == null)
            return 0;

        string matchJoinCondition = CommonUtil<T>.GetJoinConditionSql(context, condition, pkColumnNames, "s", "t");
        string pkJoinCondition = CommonUtil<T>.GetJoinConditionSql(context, null, pkColumnNames, "s", "t");
        string joinClause = matchJoinCondition == pkJoinCondition
            ? matchJoinCondition
            : $"({matchJoinCondition}) OR ({pkJoinCondition})";

        string setExpression = softDeleteColumns.ToSqlConstantUpdateSetExpression(context, "t");
        string updateSql = $@"UPDATE {tableName} t SET {setExpression}
WHERE NOT EXISTS (SELECT 1 FROM {stagingTableName} s WHERE {joinClause})";

        return ExecuteNonQuery(context, updateSql);
    }

    private static int ExecuteSoftDeleteUnmatchedForMappedTables<T>(DbContext context, TableMapping tableMapping, string stagingTableName, Expression<Func<T, T, bool>> condition, string[] pkColumnNames, Expression<Func<T, object>> softDeleteColumns)
    {
        var entityType = tableMapping.EntityType;
        var tableName = context.DelimitIdentifier(entityType.GetTableName(), entityType.GetSchema() ?? context.Database.GetDefaultSchema());
        return ExecuteSoftDeleteUnmatched<T>(context, tableName, stagingTableName, condition, pkColumnNames, softDeleteColumns);
    }

    private static int ExecuteDeleteUnmatched<T>(DbContext context, TableMapping tableMapping, string stagingTableName, Expression<Func<T, T, bool>> condition, string[] pkColumnNames)
        => ExecuteDeleteUnmatchedForMappedTables<T>(context, tableMapping, stagingTableName, condition, pkColumnNames);

    private static int ExecuteSoftDeleteUnmatched<T>(DbContext context, TableMapping tableMapping, string stagingTableName, Expression<Func<T, T, bool>> condition, string[] pkColumnNames, Expression<Func<T, object>> softDeleteColumns)
        => ExecuteSoftDeleteUnmatchedForMappedTables<T>(context, tableMapping, stagingTableName, condition, pkColumnNames, softDeleteColumns);

    private static string GetOracleColumnType(IProperty property)
    {
        var storeType = property.GetRelationalTypeMapping()?.StoreType;
        if (!string.IsNullOrWhiteSpace(storeType))
            return SanitizeOracleColumnType(storeType);

        return GetOracleDataType(property.ClrType);
    }

    private static string SanitizeOracleColumnType(string storeType)
    {
        int cutIndex = storeType.Length;
        foreach (var keyword in new[] { " GENERATED", " DEFAULT", " IDENTITY", " VISIBLE", " NOT NULL" })
        {
            int index = storeType.IndexOf(keyword, StringComparison.OrdinalIgnoreCase);
            if (index >= 0 && index < cutIndex)
                cutIndex = index;
        }

        var sanitized = storeType[..cutIndex].TrimEnd();
        if (string.Equals(sanitized, "BOOLEAN", StringComparison.OrdinalIgnoreCase))
            return "NUMBER(1)";

        if (sanitized.StartsWith("DECIMAL", StringComparison.OrdinalIgnoreCase))
            return "NUMBER" + sanitized["DECIMAL".Length..];

        return sanitized;
    }

    private static string GetOracleDataType(Type clrType)
    {
        var underlyingType = Nullable.GetUnderlyingType(clrType) ?? clrType;

        return underlyingType switch
        {
            _ when underlyingType == typeof(int) => "NUMBER(10)",
            _ when underlyingType == typeof(long) => "NUMBER(19)",
            _ when underlyingType == typeof(short) => "NUMBER(5)",
            _ when underlyingType == typeof(byte) => "NUMBER(3)",
            _ when underlyingType == typeof(decimal) => "NUMBER(18,2)",
            _ when underlyingType == typeof(double) => "BINARY_DOUBLE",
            _ when underlyingType == typeof(float) => "BINARY_FLOAT",
            _ when underlyingType == typeof(bool) => "NUMBER(1)",
            _ when underlyingType == typeof(string) => "NVARCHAR2(4000)",
            _ when underlyingType == typeof(DateTime) => "TIMESTAMP",
            _ when underlyingType == typeof(Guid) => "RAW(16)",
            _ when underlyingType.IsEnum => "NUMBER(10)",
            _ => "NVARCHAR2(4000)"
        };
    }

    internal static int BulkDelete<T>(DbContext context, IEnumerable<T> entities, BulkDeleteOptions<T> options)
    {
        var items = entities?.ToList() ?? [];
        if (items.Count == 0)
            return 0;

        var tableMapping = context.GetTableMapping(typeof(T), options?.EntityType);
        var pkColumnNames = tableMapping.GetPrimaryKeyColumns().ToArray();
        if (pkColumnNames.Length == 0 && options?.DeleteOnCondition == null)
            throw new InvalidDataException("BulkDelete requires that the entity have a primary key or the Options.DeleteOnCondition must be set.");

        var matchingColumnNames = GetMatchingColumnNames(tableMapping, options?.DeleteOnCondition).ToList();
        if (matchingColumnNames.Count == 0)
            return 0;

        var softDeleteColumnNames = options?.SoftDeleteColumns?.GetObjectProperties() ?? [];
        var columnsToLoad = softDeleteColumnNames.Count > 0
            ? matchingColumnNames.Concat(softDeleteColumnNames).Distinct(StringComparer.OrdinalIgnoreCase).ToList()
            : matchingColumnNames;

        bool usePermanentTable = options?.UsePermanentTable ?? false;
        string stagingTableName = CreateStagingTable(context, tableMapping, usePermanentTable: usePermanentTable);
        try
        {
            ExecuteOracleBulkCopy(context, items, tableMapping, columnsToLoad, options?.CommandTimeout, stagingTableName);
            if (options?.SoftDeleteColumns != null)
                return ExecuteSoftDeleteFromStagingForMappedTables(context, tableMapping, stagingTableName, options?.DeleteOnCondition, pkColumnNames, softDeleteColumnNames);
            return ExecuteDeleteFromStagingForMappedTables<T>(context, tableMapping, stagingTableName, options?.DeleteOnCondition, pkColumnNames);
        }
        finally
        {
            DropStagingTable(context, stagingTableName, usePermanentTable);
        }
    }

    internal static int BulkUpdate<T>(DbContext context, IEnumerable<T> entities, BulkUpdateOptions<T> options)
    {
        var items = entities?.ToList() ?? [];
        if (items.Count == 0)
            return 0;

        var tableMapping = context.GetTableMapping(typeof(T), options?.EntityType);
        var pkColumnNames = tableMapping.GetPrimaryKeyColumns().ToArray();
        if (pkColumnNames.Length == 0 && options?.UpdateOnCondition == null)
            throw new InvalidDataException("BulkUpdate requires that the entity have a primary key or the Options.UpdateOnCondition must be set.");

        var updatableColumns = GetUpdatableColumns(tableMapping, options?.InputColumns, options?.IgnoreColumns);
        var matchingColumnNames = GetMatchingColumnNames(tableMapping, options?.UpdateOnCondition).ToList();

        var columnsToLoad = matchingColumnNames.Concat(updatableColumns).Distinct(StringComparer.OrdinalIgnoreCase).ToList();
        if (columnsToLoad.Count == 0)
            return 0;

        bool usePermanentTable = options?.UsePermanentTable ?? false;
        string stagingTableName = CreateStagingTable(context, tableMapping, usePermanentTable: usePermanentTable);
        try
        {
            ExecuteOracleBulkCopy(context, items, tableMapping, columnsToLoad, options?.CommandTimeout, stagingTableName);
            return ExecuteMergeForUpdateForMappedTables(context, tableMapping, stagingTableName, options?.UpdateOnCondition, pkColumnNames, updatableColumns);
        }
        finally
        {
            DropStagingTable(context, stagingTableName, usePermanentTable);
        }
    }

    internal static BulkMergeResult<T> BulkMerge<T>(DbContext context, IEnumerable<T> entities, BulkMergeOptions<T> options)
    {
        var items = entities?.ToList() ?? [];
        if (items.Count == 0)
        {
            return new BulkMergeResult<T>
            {
                RowsAffected = 0,
                RowsInserted = 0,
                RowsUpdated = 0,
                RowsDeleted = 0,
                Output = []
            };
        }

        var tableMapping = context.GetTableMapping(typeof(T), options?.EntityType);
        ValidateBulkMerge(tableMapping, options?.MergeOnCondition);

        var pkColumnNames = tableMapping.GetPrimaryKeyColumns().ToArray();
        var matchingColumnNames = GetMatchingColumnNames(tableMapping, options?.MergeOnCondition).ToList();
        var insertColumns = GetInsertColumns(tableMapping, options?.InputColumnsOnInsert, options?.IgnoreColumnsOnInsert, false);
        var updatableColumns = GetUpdatableColumns(tableMapping, options?.InputColumnsOnUpdate, options?.IgnoreColumnsOnUpdate);

        var columnsToLoad = matchingColumnNames.Concat(insertColumns).Concat(updatableColumns).Distinct(StringComparer.OrdinalIgnoreCase).ToList();
        if (columnsToLoad.Count == 0)
        {
            return new BulkMergeResult<T>
            {
                RowsAffected = 0,
                RowsInserted = 0,
                RowsUpdated = 0,
                RowsDeleted = 0,
                Output = []
            };
        }

        bool usePermanentTable = options?.UsePermanentTable ?? false;
        bool autoMapOutput = options?.AutoMapOutput ?? false;
        string stagingTableName = CreateStagingTable(context, tableMapping, autoMapOutput, usePermanentTable);
        Dictionary<long, T> entityMap = autoMapOutput ? [] : null;
        try
        {
            foreach (var item in items)
                ApplyInsertColumnRules(item!, tableMapping, insertColumns, false);
            ApplyInsertDefaults(context, tableMapping, items, false);

            if (autoMapOutput)
                ExecuteOracleBulkCopy(context, items, tableMapping, columnsToLoad, options?.CommandTimeout, stagingTableName, true, entityMap);
            else
                ExecuteOracleBulkCopy(context, items, tableMapping, columnsToLoad, options?.CommandTimeout, stagingTableName);

            var outputRows = new List<BulkMergeOutputRow<T>>();
            HashSet<int> matchedIds = autoMapOutput && updatableColumns.Any()
                ? GetMatchedInternalIds<T>(context, tableMapping, stagingTableName, options?.MergeOnCondition, pkColumnNames, options)
                : [];

            (int rowsInserted, int rowsUpdated) = ExecuteMergeForMergeForMappedTables(
                context, tableMapping, stagingTableName, options?.MergeOnCondition, pkColumnNames, insertColumns, updatableColumns);

            if (autoMapOutput && entityMap != null)
                MapAutoGeneratedValuesAfterMerge(context, tableMapping, stagingTableName, options?.MergeOnCondition, pkColumnNames, entityMap, matchedIds, outputRows, options);

            int rowsDeleted = 0;
            if (options?.DeleteIfNotMatched == true)
            {
                rowsDeleted = options.SoftDeleteColumns != null
                    ? ExecuteSoftDeleteUnmatched(context, tableMapping, stagingTableName, options?.MergeOnCondition, pkColumnNames, options.SoftDeleteColumns)
                    : ExecuteDeleteUnmatched(context, tableMapping, stagingTableName, options?.MergeOnCondition, pkColumnNames);
            }

            return new BulkMergeResult<T>
            {
                RowsAffected = rowsInserted + rowsUpdated + rowsDeleted,
                RowsInserted = rowsInserted,
                RowsUpdated = rowsUpdated,
                RowsDeleted = rowsDeleted,
                Output = outputRows
            };
        }
        finally
        {
            DropStagingTable(context, stagingTableName, usePermanentTable);
        }
    }

    internal static BulkSyncResult<T> BulkSync<T>(DbContext context, IEnumerable<T> entities, BulkSyncOptions<T> options)
    {
        var items = entities?.ToList() ?? [];
        if (items.Count == 0)
        {
            return new BulkSyncResult<T>
            {
                RowsAffected = 0,
                RowsInserted = 0,
                RowsUpdated = 0,
                RowsDeleted = 0
            };
        }

        var tableMapping = context.GetTableMapping(typeof(T), options?.EntityType);
        ValidateBulkMerge(tableMapping, options?.MergeOnCondition);

        var pkColumnNames = tableMapping.GetPrimaryKeyColumns().ToArray();
        var matchingColumnNames = GetMatchingColumnNames(tableMapping, options?.MergeOnCondition).ToList();
        var insertColumns = GetInsertColumns(tableMapping, options?.InputColumnsOnInsert, options?.IgnoreColumnsOnInsert, false);
        var updatableColumns = GetUpdatableColumns(tableMapping, options?.InputColumnsOnUpdate, options?.IgnoreColumnsOnUpdate);

        var columnsToLoad = matchingColumnNames.Concat(insertColumns).Concat(updatableColumns).Distinct(StringComparer.OrdinalIgnoreCase).ToList();
        if (columnsToLoad.Count == 0)
        {
            return new BulkSyncResult<T>
            {
                RowsAffected = 0,
                RowsInserted = 0,
                RowsUpdated = 0,
                RowsDeleted = 0
            };
        }

        bool usePermanentTable = options?.UsePermanentTable ?? false;
        string stagingTableName = CreateStagingTable(context, tableMapping, usePermanentTable: usePermanentTable);
        try
        {
            foreach (var item in items)
                ApplyInsertColumnRules(item!, tableMapping, insertColumns, false);
            ApplyInsertDefaults(context, tableMapping, items, false);

            ExecuteOracleBulkCopy(context, items, tableMapping, columnsToLoad, options?.CommandTimeout, stagingTableName);

            (int rowsInserted, int rowsUpdated) = ExecuteMergeForMergeForMappedTables(
                context, tableMapping, stagingTableName, options?.MergeOnCondition, pkColumnNames, insertColumns, updatableColumns);

            int rowsDeleted = options?.SoftDeleteColumns != null
                ? ExecuteSoftDeleteUnmatched(context, tableMapping, stagingTableName, options?.MergeOnCondition, pkColumnNames, options.SoftDeleteColumns)
                : ExecuteDeleteUnmatched(context, tableMapping, stagingTableName, options?.MergeOnCondition, pkColumnNames);

            return new BulkSyncResult<T>
            {
                RowsAffected = rowsInserted + rowsUpdated + rowsDeleted,
                RowsInserted = rowsInserted,
                RowsUpdated = rowsUpdated,
                RowsDeleted = rowsDeleted
            };
        }
        finally
        {
            DropStagingTable(context, stagingTableName, usePermanentTable);
        }
    }

    internal static IEnumerable<T> BulkFetch<T, U>(DbContext context, DbSet<T> dbSet, IEnumerable<U> entities, BulkFetchOptions<T> options) where T : class, new()
    {
        var sourceItems = entities?.ToList() ?? [];
        if (sourceItems.Count == 0)
            return [];

        var tableMapping = context.GetTableMapping(typeof(T));
        using var dbTransactionContext = new DbTransactionContext(context, options?.CommandTimeout, ConnectionBehavior.New);
        string stagingTableName = string.Empty;
        string selectSql;
        try
        {
            string destinationTableName = context.DelimitIdentifier(tableMapping.TableName, tableMapping.Schema);
            string[] keyColumnNames = options?.JoinOnCondition != null
                ? CommonUtil<T>.GetColumns(options.JoinOnCondition, ["s"])
                : tableMapping.GetPrimaryKeyColumns().ToArray();

            if (keyColumnNames.Length == 0 && options?.JoinOnCondition == null)
                throw new InvalidDataException("BulkFetch requires that the entity have a primary key or the Options.JoinOnCondition must be set.");

            IEnumerable<string> columnNames = CommonUtil.FilterColumns<T>(tableMapping.GetColumns(true), keyColumnNames, options?.InputColumns, options?.IgnoreColumns);
            IEnumerable<string> columnsToFetch = CommonUtil.FormatColumns(context, "t", columnNames);

            stagingTableName = $"STG_FETCH_{tableMapping.TableName}_{Guid.NewGuid().ToString("N")[..8]}";
            context.Database.CloneTable(destinationTableName, stagingTableName, keyColumnNames);
            ExecuteOracleBulkCopy(context, sourceItems, tableMapping, keyColumnNames, options?.CommandTimeout, stagingTableName);
            selectSql = $"SELECT {string.Join(",", columnsToFetch)} FROM {stagingTableName} s JOIN {destinationTableName} t ON {CommonUtil<T>.GetJoinConditionSql(context, options?.JoinOnCondition, keyColumnNames)}";
            dbTransactionContext.Commit();
        }
        catch
        {
            dbTransactionContext.Rollback();
            throw;
        }

        List<T> items;
        try
        {
            items = context.FetchInternal<T>(selectSql).ToList();
        }
        finally
        {
            if (!string.IsNullOrEmpty(stagingTableName))
                context.Database.DropTable(stagingTableName, ifExists: true);
        }

        if (options?.AttachToContext == true)
        {
            foreach (var item in items)
                context.Attach(item);
        }

        return items;
    }

    private static void ApplyInsertDefaults<T>(DbContext context, TableMapping tableMapping, IReadOnlyCollection<T> items, bool keepIdentity)
    {
        if (items.Count == 0)
            return;

        var keyProperty = tableMapping.EntityType.FindPrimaryKey()?.Properties.FirstOrDefault();
        long generatedKey = 1;
        HashSet<long> usedKeys = null;
        if (!keepIdentity && keyProperty != null && IsNumericKey(keyProperty.ClrType))
        {
            usedKeys = [];
            foreach (var item in items)
            {
                var current = GetPropertyValue(item!, keyProperty.Name);
                if (!IsDefaultValue(current, keyProperty.ClrType))
                    usedKeys.Add(Convert.ToInt64(current));
            }

            generatedKey = GetNextNumericKey(context, tableMapping, keyProperty);
            while (usedKeys.Contains(generatedKey))
                generatedKey++;
        }

        foreach (var item in items)
        {
            foreach (var complexProperty in tableMapping.EntityType.GetComplexProperties())
            {
                if (complexProperty.IsNullable)
                    continue;

                if (GetPropertyValue(item!, complexProperty.Name) == null)
                    SetPropertyValue(item!, complexProperty.Name, Activator.CreateInstance(complexProperty.ClrType));
            }

            if (keyProperty != null && !keepIdentity && IsNumericKey(keyProperty.ClrType))
            {
                var current = GetPropertyValue(item!, keyProperty.Name);
                if (IsDefaultValue(current, keyProperty.ClrType) || Convert.ToDecimal(current) <= 0)
                {
                    while (usedKeys.Contains(generatedKey))
                        generatedKey++;

                    SetPropertyValue(item!, keyProperty.Name, ConvertKey(generatedKey, keyProperty.ClrType));
                    usedKeys.Add(generatedKey);
                    generatedKey++;
                }
            }

            foreach (var property in tableMapping.GetEntityProperties(valueGenerated: ValueGenerated.OnAdd).Concat(tableMapping.GetEntityProperties(valueGenerated: ValueGenerated.OnAddOrUpdate)))
            {
                if (property.Name == keyProperty?.Name)
                    continue;

                if (property.GetDefaultValueSql() != null || property.GetDefaultValue() != null)
                    continue;

                if (property.ClrType == typeof(DateTime) || property.ClrType == typeof(DateTime?))
                {
                    if (IsDefaultValue(GetPropertyValue(item!, property.Name), property.ClrType))
                        SetPropertyValue(item!, property.Name, DateTime.Now);
                }
                else if (property.ClrType == typeof(bool) || property.ClrType == typeof(bool?))
                {
                    if (IsDefaultValue(GetPropertyValue(item!, property.Name), property.ClrType))
                        SetPropertyValue(item!, property.Name, true);
                }
            }
        }
    }

    private static IEnumerable<string> GetMatchingPropertyNames<T>(TableMapping tableMapping, Expression<Func<T, T, bool>> condition)
    {
        var propertyNames = condition != null ? CommonUtil<T>.GetColumns(condition, ["s"]) : [];
        if (propertyNames.Length > 0)
            return propertyNames;
        return tableMapping.EntityType.FindPrimaryKey()?.Properties.Select(p => p.Name) ?? [];
    }

    private static IEnumerable<string> GetMatchingColumnNames<T>(TableMapping tableMapping, Expression<Func<T, T, bool>> condition)
    {
        return GetMatchingPropertyNames(tableMapping, condition)
            .Select(name =>
            {
                var property = tableMapping.Properties.FirstOrDefault(p => string.Equals(p.Name, name, StringComparison.OrdinalIgnoreCase));
                return property != null ? tableMapping.GetColumnName(property) : name;
            });
    }

    private static void ValidateBulkMerge(TableMapping tableMapping, LambdaExpression mergeOnCondition)
    {
        if (!tableMapping.GetPrimaryKeyColumns().Any() && mergeOnCondition == null)
            throw new InvalidDataException("BulkMerge requires that the entity have a primary key or that Options.MergeOnCondition be set");
    }

    private static List<T> FilterInsertItems<T>(DbContext context, TableMapping tableMapping, List<T> items, BulkInsertOptions<T> options)
    {
        if (options?.InsertOnCondition != null)
        {
            var matchPropertyNames = GetMatchingPropertyNames(tableMapping, options.InsertOnCondition).ToList();
            if (matchPropertyNames.Count == 0)
                return items;

            var existingRows = GetSet<T>(context).Cast<T>().AsEnumerable().ToList();
            return items.Where(item => !existingRows.Any(existing => MatchesCondition(item, existing, matchPropertyNames))).ToList();
        }

        if (options?.InsertIfNotExists == true)
        {
            var keyProperty = tableMapping.EntityType.FindPrimaryKey()?.Properties.SingleOrDefault();
            if (keyProperty == null)
                return items;

            var existingKeys = GetSet<T>(context).Cast<T>()
                .AsEnumerable()
                .Select(entity => GetPropertyValue(entity!, keyProperty.Name))
                .Where(value => value != null)
                .Select(value => value.ToString())
                .ToHashSet(StringComparer.OrdinalIgnoreCase);

            return items.Where(item =>
            {
                var keyValue = GetPropertyValue(item!, keyProperty.Name);
                return keyValue == null || !existingKeys.Contains(keyValue.ToString());
            }).ToList();
        }

        return items;
    }

    private static IProperty GetIdentityPrimaryKeyProperty(TableMapping tableMapping)
    {
        var pk = tableMapping.EntityType.FindPrimaryKey();
        if (pk == null || pk.Properties.Count != 1)
            return null;
        var property = pk.Properties[0];
        return property.ValueGenerated != ValueGenerated.Never ? property : null;
    }

    private static object ReadMaxIdentityValue(DbContext context, TableMapping tableMapping, IProperty identityProperty)
    {
        string columnName = tableMapping.GetColumnName(identityProperty);
        var declaringEntityType = identityProperty.DeclaringType ?? tableMapping.EntityType;
        string tableName = context.DelimitIdentifier(declaringEntityType.GetTableName(), declaringEntityType.GetSchema() ?? context.Database.GetDefaultSchema());
        string sql = $"SELECT MAX({context.DelimitIdentifier(columnName)}) FROM {tableName}";
        var connection = context.Database.GetDbConnection();
        if (connection.State != ConnectionState.Open)
            connection.Open();

        using var command = connection.CreateCommand();
        ConfigureCommand(context, command, sql, null);
        var value = command.ExecuteScalar();
        return value == null || value == DBNull.Value ? null : value;
    }

    private static void MapAutoGeneratedValuesAfterInsert<T>(DbContext context, TableMapping tableMapping, IReadOnlyCollection<T> items, bool keepIdentity, IProperty identityProperty, object maxIdentityBefore)
    {
        if (items.Count == 0)
            return;

        var storeGeneratedProperties = tableMapping.GetEntityProperties(valueGenerated: ValueGenerated.OnAdd)
            .Concat(tableMapping.GetEntityProperties(valueGenerated: ValueGenerated.OnAddOrUpdate))
            .ToList();
        if (storeGeneratedProperties.Count == 0)
            return;

        if (!keepIdentity && identityProperty != null)
        {
            if (IsNumericKey(identityProperty.ClrType))
            {
                string columnName = tableMapping.GetColumnName(identityProperty);
                var declaringEntityType = identityProperty.DeclaringType ?? tableMapping.EntityType;
                string tableName = context.DelimitIdentifier(declaringEntityType.GetTableName(), declaringEntityType.GetSchema() ?? context.Database.GetDefaultSchema());
                string maxFilter = maxIdentityBefore == null || maxIdentityBefore is DBNull
                    ? "1=1"
                    : $"{context.DelimitIdentifier(columnName)} > {Convert.ToString(maxIdentityBefore, System.Globalization.CultureInfo.InvariantCulture)}";
                string sql = $"SELECT {context.DelimitIdentifier(columnName)} FROM {tableName} WHERE {maxFilter} ORDER BY {context.DelimitIdentifier(columnName)}";
                var queryResult = context.BulkQuery(sql, null);
                var generatedIds = queryResult.Results.Select(r => r[0]).ToList();
                int index = 0;
                foreach (var item in items)
                {
                    if (index >= generatedIds.Count)
                        break;
                    var current = GetPropertyValue(item!, identityProperty.Name);
                    if (IsDefaultValue(current, identityProperty.ClrType) || (IsNumericKey(identityProperty.ClrType) && Convert.ToDecimal(current) <= 0))
                    {
                        object generated = ConvertDbValue(generatedIds[index], identityProperty);
                        context.SetStoreGeneratedValues(item, [identityProperty], [generated]);
                        index++;
                    }
                }
            }
            else if (identityProperty.ClrType == typeof(Guid) || identityProperty.ClrType == typeof(Guid?))
            {
                var itemsNeedingIds = items.Where(item => IsDefaultValue(GetPropertyValue(item!, identityProperty.Name), identityProperty.ClrType)).ToList();
                if (itemsNeedingIds.Count == 0)
                    return;

                string columnName = tableMapping.GetColumnName(identityProperty);
                var declaringEntityType = identityProperty.DeclaringType ?? tableMapping.EntityType;
                string tableName = context.DelimitIdentifier(declaringEntityType.GetTableName(), declaringEntityType.GetSchema() ?? context.Database.GetDefaultSchema());
                string sql = $"SELECT {context.DelimitIdentifier(columnName)} FROM {tableName} ORDER BY ROWID DESC FETCH FIRST {itemsNeedingIds.Count} ROWS ONLY";
                var queryResult = context.BulkQuery(sql, null);
                var generatedIds = queryResult.Results.Select(r => r[0]).Reverse().ToList();
                for (int index = 0; index < itemsNeedingIds.Count && index < generatedIds.Count; index++)
                {
                    object generated = ConvertDbValue(generatedIds[index], identityProperty);
                    context.SetStoreGeneratedValues(itemsNeedingIds[index], [identityProperty], [generated]);
                }
            }
        }
    }

    private static HashSet<int> GetMatchedInternalIds<T>(DbContext context, TableMapping tableMapping, string stagingTableName, Expression<Func<T, T, bool>> condition, string[] pkColumnNames, BulkOptions options)
    {
        string targetTableName = tableMapping.FullQualifedTableName;
        string joinCondition = CommonUtil<T>.GetJoinConditionSql(context, condition, pkColumnNames, "s", "t");
        string sql = $"SELECT {context.DelimitMemberAccess("s", Constants.InternalId_ColumnName)} FROM {stagingTableName} s JOIN {targetTableName} t ON {joinCondition}";
        var results = context.BulkQuery(sql, options);
        return results.Results.Select(r => Convert.ToInt32(r[0])).ToHashSet();
    }

    private static void MapAutoGeneratedValuesAfterMerge<T>(DbContext context, TableMapping tableMapping, string stagingTableName, Expression<Func<T, T, bool>> condition, string[] pkColumnNames, Dictionary<long, T> entityMap, HashSet<int> matchedIds, List<BulkMergeOutputRow<T>> outputRows, BulkOptions options)
    {
        string targetTableName = tableMapping.FullQualifedTableName;
        string joinCondition = CommonUtil<T>.GetJoinConditionSql(context, condition, pkColumnNames, "s", "t");
        var autoGeneratedColumns = tableMapping.GetAutoGeneratedColumns().ToList();
        var allProperties = tableMapping.GetEntityProperties(valueGenerated: ValueGenerated.OnAdd)
            .Concat(tableMapping.GetEntityProperties(valueGenerated: ValueGenerated.OnAddOrUpdate))
            .ToList();

        string outputColumnsSql = autoGeneratedColumns.Count > 0
            ? "," + string.Join(",", autoGeneratedColumns.Select(c => context.DelimitMemberAccess("t", c)))
            : string.Empty;
        string outputQuery = $"SELECT {context.DelimitMemberAccess("s", Constants.InternalId_ColumnName)}{outputColumnsSql} FROM {stagingTableName} s JOIN {targetTableName} t ON {joinCondition}";
        var bulkQueryResult = context.BulkQuery(outputQuery, options);

        foreach (var result in bulkQueryResult.Results)
        {
            int entityId = Convert.ToInt32(result[0]);
            bool wasMatched = matchedIds.Contains(entityId);
            string action = wasMatched ? SqlMergeAction.Update : SqlMergeAction.Insert;
            outputRows.Add(new BulkMergeOutputRow<T>(action));

            if (entityMap.TryGetValue(entityId, out var entity) && allProperties.Count > 0 && autoGeneratedColumns.Count > 0)
            {
                object[] entityValues = allProperties
                    .Select(p =>
                    {
                        string columnName = tableMapping.GetColumnName(p);
                        int columnIndex = autoGeneratedColumns.FindIndex(c => string.Equals(c, columnName, StringComparison.OrdinalIgnoreCase));
                        return columnIndex >= 0
                            ? ConvertDbValue(result[1 + columnIndex], p)
                            : GetPropertyValue(entity, p);
                    })
                    .ToArray();
                context.SetStoreGeneratedValues(entity, allProperties, entityValues);
            }
        }
    }

    private static HashSet<string> GetMergeOnColumnNames<T>(TableMapping tableMapping, Expression<Func<T, T, bool>> condition, string[] pkColumnNames)
    {
        var onColumns = new HashSet<string>(pkColumnNames ?? [], StringComparer.OrdinalIgnoreCase);
        if (condition != null)
        {
            foreach (var propertyName in condition.GetPredicatePropertyNames())
            {
                var property = tableMapping.Properties.FirstOrDefault(p => string.Equals(p.Name, propertyName, StringComparison.OrdinalIgnoreCase));
                onColumns.Add(property != null ? tableMapping.GetColumnName(property) : propertyName);
            }
        }

        return onColumns;
    }

    private static object ConvertDbValue(object value, IProperty property)
    {
        if (value == null || value == DBNull.Value)
            return null;

        var clrType = Nullable.GetUnderlyingType(property.ClrType) ?? property.ClrType;

        if (clrType.IsInstanceOfType(value))
            return value;

        if (clrType == typeof(Guid))
        {
            if (value is byte[] bytes)
                return new Guid(bytes);
            if (value is string s && Guid.TryParse(s, out var guid))
                return guid;
        }

        if (value is decimal dec)
        {
            if (clrType == typeof(long)) return Convert.ToInt64(dec);
            if (clrType == typeof(int)) return Convert.ToInt32(dec);
            if (clrType == typeof(short)) return Convert.ToInt16(dec);
            if (clrType == typeof(byte)) return Convert.ToByte(dec);
        }

        return Convert.ChangeType(value, clrType);
    }

    private static IEnumerable<string> GetMatchingColumns<T>(Expression<Func<T, T, bool>> condition, params string[] fallbackPropertyNames)
    {
        var columns = condition != null ? CommonUtil<T>.GetColumns(condition, ["s"]) : [];
        if (columns.Length > 0)
            return columns;
        return fallbackPropertyNames ?? [];
    }

    private static IEnumerable<string> GetUpdatableColumns<T>(TableMapping tableMapping, Expression<Func<T, object>> inputColumns, Expression<Func<T, object>> ignoreColumns)
    {
        var includedColumns = tableMapping.GetColumns(false).ToHashSet(StringComparer.OrdinalIgnoreCase);
        if (inputColumns != null)
        {
            includedColumns.IntersectWith(inputColumns.GetObjectProperties());
        }

        if (ignoreColumns != null)
        {
            foreach (var ignored in ignoreColumns.GetObjectProperties())
                includedColumns.Remove(ignored);
        }

        return includedColumns;
    }

    private static IEnumerable<string> GetInsertColumns<T>(TableMapping tableMapping, Expression<Func<T, object>> inputColumns, Expression<Func<T, object>> ignoreColumns, bool keepIdentity)
    {
        var includedColumns = tableMapping.GetColumns(true).ToHashSet(StringComparer.OrdinalIgnoreCase);
        if (inputColumns != null)
        {
            includedColumns.IntersectWith(inputColumns.GetObjectProperties());
        }

        if (ignoreColumns != null)
        {
            includedColumns.ExceptWith(ignoreColumns.GetObjectProperties());
        }

        var primaryKey = tableMapping.EntityType.FindPrimaryKey();
        if (keepIdentity)
        {
            foreach (var key in primaryKey?.Properties ?? [])
                includedColumns.Add(tableMapping.GetColumnName(key));
        }
        else
        {
            foreach (var key in primaryKey?.Properties.Where(o => IsNumericKey(o.ClrType)) ?? [])
                includedColumns.Add(tableMapping.GetColumnName(key));
        }

        return includedColumns;
    }

    private static T FindMatch<T, U>(IEnumerable<T> candidates, U source, IEnumerable<string> matchingColumns)
    {
        foreach (var candidate in candidates)
        {
            if (MatchesCondition(source, candidate, matchingColumns))
                return candidate;
        }

        return default;
    }

    private static bool MatchesCondition<U, T>(U source, T target, IEnumerable<string> columns)
    {
        if (columns == null)
            return false;

        foreach (var column in columns)
        {
            var sourceValue = GetPropertyValue(source, column);
            var targetValue = GetPropertyValue(target, column);
            if (sourceValue == null || targetValue == null || !Equals(sourceValue, targetValue))
                return false;
        }

        return columns.Any();
    }

    private static void CopyKeyValues<T>(T source, T target, TableMapping tableMapping)
    {
        if (source == null || target == null)
            return;

        var keyNames = tableMapping.GetPrimaryKeyColumns().ToHashSet(StringComparer.OrdinalIgnoreCase);
        foreach (var property in source.GetType().GetProperties().Where(o => o.CanRead && o.CanWrite))
        {
            if (!keyNames.Contains(property.Name))
                continue;

            var targetProperty = target.GetType().GetProperty(property.Name);
            if (targetProperty?.CanWrite == true)
                targetProperty.SetValue(target, property.GetValue(source));
        }
    }

    private static void ClearExcludedColumns<T>(TableMapping tableMapping, T entity, IEnumerable<string> includedColumns, IEnumerable<string> ignoredColumns)
    {
        var included = includedColumns?.ToHashSet(StringComparer.OrdinalIgnoreCase) ?? [];
        var ignored = ignoredColumns?.ToHashSet(StringComparer.OrdinalIgnoreCase) ?? [];

        foreach (var property in tableMapping.Properties)
        {
            if (tableMapping.GetPrimaryKeyColumns().Contains(property.Name))
                continue;

            if (ignored.Contains(property.Name) || !included.Contains(property.Name))
            {
                SetPropertyValue(entity!, property.Name, GetDefaultValue(property.ClrType));
            }
        }
    }

    private static void ApplyInsertColumnRules<T>(T entity, TableMapping tableMapping, IEnumerable<string> allowedColumns, bool keepIdentity)
    {
        var allowed = allowedColumns?.ToHashSet(StringComparer.OrdinalIgnoreCase) ?? [];
        var keyNames = tableMapping.GetPrimaryKeyColumns().ToHashSet(StringComparer.OrdinalIgnoreCase);

        foreach (var property in tableMapping.Properties)
        {
            if (keyNames.Contains(property.Name) && !keepIdentity)
                continue;

            if (allowed.Count > 0 && !allowed.Contains(property.Name))
                SetPropertyValue(entity!, property.Name, GetDefaultValue(property.ClrType));
        }
    }

    private static void ApplyUpdateColumnRules(EntityEntry entry, IEnumerable<string> updatableColumns)
    {
        var allowed = updatableColumns?.ToHashSet(StringComparer.OrdinalIgnoreCase) ?? [];
        foreach (var property in entry.Properties)
        {
            if (property.Metadata.IsPrimaryKey())
                continue;

            if (allowed.Count > 0 && !allowed.Contains(property.Metadata.Name))
            {
                property.CurrentValue = property.OriginalValue;
                property.IsModified = false;
            }
        }
    }

    private static object GetPropertyValue(object entity, string propertyName)
    {
        if (entity == null)
            return null;

        if (entity is InternalEntityEntry internalEntry)
            return internalEntry.ToEntityEntry().CurrentValues[propertyName];

        if (entity is EntityEntry entry)
            return entry.CurrentValues[propertyName];

        var property = entity.GetType().GetProperty(propertyName);
        return property?.GetValue(entity);
    }

    private static object GetPropertyValue(object entity, IProperty property)
    {
        if (entity == null || property == null)
            return null;

        object value;
        if (property.DeclaringType is IComplexType complexType)
        {
            var complexObject = ReadMember(entity, complexType.ComplexProperty.Name);
            value = complexObject == null ? null : ReadMember(complexObject, property.Name);
        }
        else
        {
            value = ReadMember(entity, property.Name);
        }

        var converter = property.GetTypeMapping()?.Converter;
        if (converter != null && value != null)
            value = converter.ConvertToProvider(value);

        return value;
    }

    private static object ReadMember(object target, string memberName)
    {
        if (target == null)
            return null;

        if (target is InternalEntityEntry internalEntry)
            return internalEntry.ToEntityEntry().CurrentValues[memberName];

        if (target is EntityEntry entry)
            return entry.CurrentValues[memberName];

        var type = target.GetType();
        const BindingFlags flags = BindingFlags.Public | BindingFlags.Instance;
        var property = type.GetProperty(memberName, flags);
        if (property != null)
            return property.GetValue(target);

        var field = type.GetField(memberName, flags);
        return field?.GetValue(target);
    }

    private static void SetPropertyValue(object entity, string propertyName, object value)
    {
        if (entity is InternalEntityEntry internalEntry)
        {
            internalEntry.ToEntityEntry().CurrentValues[propertyName] = value;
            return;
        }

        if (entity is EntityEntry entry)
        {
            entry.CurrentValues[propertyName] = value;
            return;
        }

        var property = entity?.GetType().GetProperty(propertyName);
        if (property?.CanWrite == true)
            property.SetValue(entity, value);
    }

    private static bool IsDefaultValue(object value, Type type)
    {
        if (value == null)
            return true;

        var underlyingType = Nullable.GetUnderlyingType(type) ?? type;
        return Equals(value, underlyingType.IsValueType ? Activator.CreateInstance(underlyingType) : null);
    }

    private static bool IsNumericKey(Type type)
    {
        type = Nullable.GetUnderlyingType(type) ?? type;
        return type == typeof(short) || type == typeof(int) || type == typeof(long) || type == typeof(byte)
            || type == typeof(decimal) || type == typeof(double) || type == typeof(float);
    }

    private static long GetNextNumericKey<T>(DbContext context, IProperty keyProperty)
    {
        var currentValues = GetSet<T>(context).Cast<T>().ToList()
            .Select(entity => GetPropertyValue(entity!, keyProperty.Name))
            .Where(value => value != null)
            .Select(value => Convert.ToInt64(value))
            .ToList();
        return currentValues.Count == 0 ? 1 : currentValues.Max() + 1;
    }

    private static long GetNextNumericKey(DbContext context, TableMapping tableMapping, IProperty keyProperty)
    {
        var columnName = tableMapping.GetColumnName(keyProperty);
        var sql = $"SELECT MAX(\"{columnName}\") FROM {tableMapping.FullQualifedTableName}";
        var connection = context.Database.GetDbConnection();
        if (connection.State != ConnectionState.Open)
            connection.Open();

        using var command = connection.CreateCommand();
        ConfigureCommand(context, command, sql, null);
        var value = command.ExecuteScalar();
        return value == null || value == DBNull.Value ? 1 : Convert.ToInt64(value) + 1;
    }

    private static IQueryable GetSet<T>(DbContext context)
    {
        var method = typeof(DbContext).GetMethods(BindingFlags.Public | BindingFlags.Instance)
            .Single(o => o.Name == nameof(DbContext.Set) && o.IsGenericMethodDefinition && o.GetParameters().Length == 0);
        return (IQueryable)method.MakeGenericMethod(typeof(T)).Invoke(context, null);
    }

    private static object ConvertKey(long value, Type type)
    {
        type = Nullable.GetUnderlyingType(type) ?? type;
        return Convert.ChangeType(value, type);
    }

    private static object GetDefaultValue(Type type)
    {
        type = Nullable.GetUnderlyingType(type) ?? type;
        return type.IsValueType ? Activator.CreateInstance(type) : null;
    }

