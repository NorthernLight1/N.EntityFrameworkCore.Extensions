using System.Threading.Tasks;
using Microsoft.EntityFrameworkCore;
using N.EntityFrameworkCore.Extensions.Test.Data;

namespace N.EntityFrameworkCore.Extensions.Test.Common;

internal static class TestDatabaseInitializer
{
    internal static void EnsureCreated(TestDbContext dbContext)
    {
        if (Config.UseOracleContainer)
            OracleContainerManager.EnsureStarted();

        dbContext.Database.EnsureCreated();
        CreateOracleObjects(dbContext);
    }

    internal static async Task EnsureCreatedAsync(TestDbContext dbContext)
    {
        if (Config.UseOracleContainer)
            await OracleContainerManager.EnsureStartedAsync();

        await dbContext.Database.EnsureCreatedAsync();
        await CreateOracleObjectsAsync(dbContext);
    }

    /// <summary>
    /// Oracle historically relied on EnsureCreated only (no manual DDL). EnsureCreated does not
    /// add tables to an existing schema, so CREATE TABLE is issued with ORA-00955 ignored.
    /// If tables are still missing after a model change, run EnsureDeleted once against the test DB.
    /// </summary>
    internal static void CreateOracleObjects(TestDbContext dbContext)
    {
        dbContext.Database.ExecuteSqlRaw("""
            BEGIN
                EXECUTE IMMEDIATE 'CREATE TABLE GUIDKEYENTITIES ("Id" RAW(16) NOT NULL, "Name" NVARCHAR2(100), CONSTRAINT "PK_GUIDKEYENTITIES" PRIMARY KEY ("Id"))';
            EXCEPTION
                WHEN OTHERS THEN
                    IF SQLCODE != -955 THEN RAISE; END IF;
            END;
            """);
        dbContext.Database.ExecuteSqlRaw("""
            BEGIN
                EXECUTE IMMEDIATE 'CREATE TABLE BLOGS ("Id" NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL, "Title" NVARCHAR2(200), CONSTRAINT "PK_BLOGS" PRIMARY KEY ("Id"))';
            EXCEPTION
                WHEN OTHERS THEN
                    IF SQLCODE != -955 THEN RAISE; END IF;
            END;
            """);
        dbContext.Database.ExecuteSqlRaw("""
            BEGIN
                EXECUTE IMMEDIATE 'CREATE TABLE BLOGPOSTS ("Id" NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL, "Title" NVARCHAR2(200), "BlogId" NUMBER(10) NOT NULL, CONSTRAINT "PK_BLOGPOSTS" PRIMARY KEY ("Id"), CONSTRAINT "FK_BLOGPOSTS_BLOGS_BLOGID" FOREIGN KEY ("BlogId") REFERENCES BLOGS ("Id") ON DELETE CASCADE)';
            EXCEPTION
                WHEN OTHERS THEN
                    IF SQLCODE != -955 THEN RAISE; END IF;
            END;
            """);
        dbContext.Database.ExecuteSqlRaw("""
            BEGIN
                EXECUTE IMMEDIATE 'ALTER TABLE ORDERS ADD ("IsDeleted" NUMBER(1) DEFAULT 0 NOT NULL)';
            EXCEPTION
                WHEN OTHERS THEN
                    IF SQLCODE != -1430 THEN RAISE; END IF;
            END;
            """);
        dbContext.Database.ExecuteSqlRaw("""
            BEGIN
                EXECUTE IMMEDIATE 'CREATE TABLE ORDERSWITHOWNEDDETAIL ("Id" NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL, "Price" NUMBER(18,2) NOT NULL, "Detail_City" NVARCHAR2(2000), "Detail_Region" NVARCHAR2(2000), CONSTRAINT "PK_ORDERSWITHOWNEDDETAIL" PRIMARY KEY ("Id"))';
            EXCEPTION
                WHEN OTHERS THEN
                    IF SQLCODE != -955 THEN RAISE; END IF;
            END;
            """);
    }

